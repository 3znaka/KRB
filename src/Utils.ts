/**
 * Вычисляет координату Z начала тайла (северная граница) в мировой системе.
 *
 * @param y - Номер строки тайла (ось Y направлена на юг).
 * @param tileSize - Размер тайла в мировых единицах.
 * @param maxMercator - Максимальное значение координаты в проекции Меркатора.
 * @returns Z-координата начала тайла.
 *
 * @example
 * const originZ = getOriginZ(0, 256, 20037508.34);
 */
export function getOriginZ(
    y: number,
    tileSize: number,
    maxMercator: number,
): number {
    return -maxMercator + y * tileSize;
}

/**
 * Формирует строковый ключ тайла в формате "z,x,y".
 *
 * Используется как для исходных тайлов (URL), так и для виртуальных
 * экземпляров на сцене — формат идентичен.
 *
 * @param z - Уровень зума.
 * @param x - X-координата тайла (виртуальная, не обёрнутая).
 * @param y - Y-координата (строка).
 * @returns Ключ в формате "z,x,y".
 *
 * @example
 * const key = getVirtKey(5, 10, 3); // "5,10,3"
 */
export function getVirtKey(z: number, x: number, y: number): string {
    return `${z},${x},${y}`;
}

/**
 * Формирует строковый ключ для исходного тайла.
 *
 * @deprecated Дублирует `getVirtKey` — обе функции возвращают одну
 * и ту же строку. Оставлено для обратной совместимости; в новом коде
 * используйте `getVirtKey`.
 *
 * @param z - Уровень зума.
 * @param srcX - X-координата исходного тайла.
 * @param y - Y-координата (строка).
 * @returns Ключ в формате "z,srcX,y".
 */
export function getSrcKey(z: number, srcX: number, y: number): string {
    return `${z},${srcX},${y}`;
}